import { chromium } from 'playwright-core';
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome', args: ['--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
await page.goto('http://localhost:5173/?dev=1');
await page.waitForTimeout(800);
const r = await page.evaluate(async () => {
  const app = window.__app;
  app.profile.tutorialDone = true;
  app.startGame('meadow', 'sandbox', 'nova');
  await new Promise((r) => setTimeout(r, 300));
  const g = app.game;
  for (let i = 0; i < 800; i++) g.spawn(['ceramic', 'rainbow', 'zebra', 'pink', 'lead'][i % 5], { dist: 20 + i * 4 });
  g.paused = true;
  const R = app.renderer;
  R.particles.clear();
  const ctx = R.ctx;
  const time = (label, fn, frames = 30) => { const t0 = performance.now(); for (let f = 0; f < frames; f++) fn(); return [label, ((performance.now() - t0) / frames).toFixed(2)]; };
  const out = [];
  out.push(time('full', () => R.render(0)));
  const di = ctx.drawImage;
  ctx.drawImage = function () {};
  out.push(time('no drawImage', () => R.render(0)));
  ctx.drawImage = di;
  const st = ctx.setTransform;
  out.push(time('full again', () => R.render(0)));
  const fill = ctx.fill;
  ctx.fill = function () {};
  out.push(time('no fill', () => R.render(0)));
  ctx.fill = fill;
  return out;
});
console.log(r.map((x) => x.join(': ')).join('\n'));
await browser.close();
