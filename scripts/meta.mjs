import { chromium } from 'playwright-core';
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome', args: ['--no-sandbox'] });
const ctx = await browser.newContext({ viewport: { width: 1280, height: 720 }, locale: 'de-DE' });
const page = await ctx.newPage();
const logs = [];
page.on('pageerror', (e) => logs.push('PAGEERROR: ' + e.message));
await page.goto('http://localhost:5173/');
await page.evaluate(() => { localStorage.clear(); });
await page.reload();
await page.waitForTimeout(800);
await page.evaluate(() => { const a = window.__app; a.profile.xp = 9000; a.profile.stats.pops = 1500; a.showMenu(); });
await page.waitForTimeout(500);
await page.screenshot({ path: 'screens/meta-menu.png' });
await page.locator('.menu-dock .rbtn').nth(1).click();
await page.waitForTimeout(300);
await page.locator('.perk.can').first().click();
await page.waitForTimeout(200);
await page.screenshot({ path: 'screens/meta-perks.png' });
await page.locator('.modal .btn.green').click();
await page.waitForTimeout(300);
await page.locator('.menu-dock .rbtn').nth(2).click();
await page.waitForTimeout(300);
await page.screenshot({ path: 'screens/meta-ach.png' });
await page.locator('.modal .xbtn').click();
await page.waitForTimeout(300);
await page.locator('.menu-dock .rbtn').nth(0).click();
await page.waitForTimeout(300);
await page.screenshot({ path: 'screens/meta-daily.png' });
await page.locator('.modal .btn.green').click();
await page.waitForTimeout(800);
await page.screenshot({ path: 'screens/meta-dailygame.png' });
console.log(JSON.stringify(await page.evaluate(() => ({ perks: window.__app.profile.perks, ach: Object.keys(window.__app.profile.achievements), cash: window.__app.game?.cash, allowed: window.__app.game?.config.challenge?.allowed }))));
if (logs.length) console.log(logs.join('\n'));
await browser.close();
